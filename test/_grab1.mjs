import { chromium } from 'playwright';
import { writeFileSync } from 'fs';
const id = process.argv[2];
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1200, height: 900 } });
await ctx.addInitScript(() => { window.__cap = null; Object.defineProperty(navigator, 'clipboard', { value: { writeText: t => { window.__cap = t; return Promise.resolve(); } } }); });
const pg = await ctx.newPage();
await pg.goto(`https://gottkf1208.github.io/quoka-motion-lab/#${id}`); await pg.reload({ waitUntil: 'networkidle' }); await pg.waitForTimeout(800);
await pg.click('#modeSeg button[data-v="full"]'); await pg.waitForTimeout(200);
await pg.click('#btnMain'); await pg.waitForTimeout(600);
const txt = await pg.evaluate(() => window.__cap);
writeFileSync(`assets/motions/${id}.html`, txt, 'utf8'); console.log(id, txt.length);
await b.close();
