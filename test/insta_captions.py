def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")

pid = [1000000001]
def para(text, char=1, ppr=0, runs=None, page_break=0):
    pid[0] += 1
    body = "".join(f'<hp:run charPrIDRef="{c}"><hp:t>{esc(t)}</hp:t></hp:run>' for t, c in (runs or [(text, char)])) if (runs or text) else '<hp:run charPrIDRef="0"><hp:t/></hp:run>'
    return f'<hp:p id="{pid[0]}" paraPrIDRef="{ppr}" styleIDRef="0" pageBreak="{page_break}" columnBreak="0" merged="0">{body}</hp:p>'

